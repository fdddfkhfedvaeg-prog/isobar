// Regenerates supabase/migrations/0002_seed.sql from src/data/lineage.ts so the
// bundled fallback and the database never drift. Run: npm run seed:sql
import { writeFileSync } from 'node:fs'
import { LINEAGE } from '../src/data/lineage.ts'

const q = (v: string) => `'${v.replace(/'/g, "''")}'`

const chips = new Map<string, number>()
for (const m of LINEAGE) chips.set(m.chip, m.process_nm)

const chipRows = [...chips].map(([name, nm]) => `  (${q(name)}, ${nm})`).join(',\n')

const modelRows = LINEAGE.map((m) =>
  `  (${[
    q(m.slug), q(m.name), m.release_year,
    `(select id from public.chips where name = ${q(m.chip)})`,
    m.display_in, q(m.display_tech), q(m.resolution), m.refresh_hz,
    m.rear_cameras, m.main_camera_mp, m.max_optical_zoom,
    q(m.frame), m.height_mm, m.width_mm, m.depth_mm, m.weight_g,
    m.base_storage_gb, m.launch_price_usd, q(m.price_basis), m.verified,
  ].join(', ')})`,
).join(',\n')

const sql = `-- Generated by scripts/gen-seed.ts. Do not edit by hand.
insert into public.chips (name, process_nm) values
${chipRows}
on conflict (name) do update set process_nm = excluded.process_nm;

insert into public.iphone_models (
  slug, name, release_year, chip_id,
  display_in, display_tech, resolution, refresh_hz,
  rear_cameras, main_camera_mp, max_optical_zoom,
  frame, height_mm, width_mm, depth_mm, weight_g,
  base_storage_gb, launch_price_usd, price_basis, verified
) values
${modelRows}
on conflict (slug) do update set
  name = excluded.name, release_year = excluded.release_year, chip_id = excluded.chip_id,
  display_in = excluded.display_in, display_tech = excluded.display_tech,
  resolution = excluded.resolution, refresh_hz = excluded.refresh_hz,
  rear_cameras = excluded.rear_cameras, main_camera_mp = excluded.main_camera_mp,
  max_optical_zoom = excluded.max_optical_zoom, frame = excluded.frame,
  height_mm = excluded.height_mm, width_mm = excluded.width_mm, depth_mm = excluded.depth_mm,
  weight_g = excluded.weight_g, base_storage_gb = excluded.base_storage_gb,
  launch_price_usd = excluded.launch_price_usd, price_basis = excluded.price_basis,
  verified = excluded.verified;
`

writeFileSync(new URL('../supabase/migrations/0002_seed.sql', import.meta.url), sql)
console.log(`Wrote ${chips.size} chips and ${LINEAGE.length} models.`)
